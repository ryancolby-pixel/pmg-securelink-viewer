// Builds the AME request sheet the server serves at GET /sheet: viewer/sheet/index.html (one inline style, one inline
// script) and viewer/sheet/sheet-data.json (made by tools/build-sheet-data.py, FAA words only), and pins the style and
// script SHA-256 hashes for the Content-Security-Policy. Also writes viewer/sheet/sheet-links.json: each condition's id,
// name, FAA page and source URLs, and no FAA words, which the server always serves (GET /sheet/sheet-links.json) so
// the page can show links to the FAA's pages while the quotes are being re-checked. Output: src/generated/sheet.mjs (committed), so the Lambda
// and the local server serve the same bytes. The page holds no pilot data; it can fetch only its own data file.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const hash = (s) => `sha256-${createHash("sha256").update(s, "utf8").digest("base64")}`;

const html = read("viewer/sheet/index.html");
const data = read("viewer/sheet/sheet-data.json");

// Our page. The data file is the FAA's words, verbatim, so its dashes stay.
if (/\u2014|\u2013/.test(html)) throw new Error("no em or en dashes in the sheet page");
if (/<script[^>]+src=|<link[^>]+href=/i.test(html)) throw new Error("the sheet must load nothing from elsewhere");

// Exactly one bare <style> and one bare <script>, so the two hashes cover everything the page runs.
const inner = (tag) => {
  const opens = html.match(new RegExp(`<${tag}\\b[^>]*>`, "gi")) || [];
  if (opens.length !== 1 || opens[0] !== `<${tag}>`) throw new Error(`the sheet needs exactly one <${tag}> with no attributes`);
  return html.split(`<${tag}>`)[1].split(`</${tag}>`)[0];
};
const script = inner("script"), style = inner("style");
// The CSP blocks inline handlers and style attributes; refuse them here rather than ship a page that silently breaks.
const markup = html.replace(script, "").replace(style, "");
if (/\son[a-z]+\s*=|\sstyle\s*=/i.test(markup)) throw new Error("no inline event handlers or style attributes in the sheet");

const parsed = JSON.parse(data);
if (!Array.isArray(parsed.conditions) || parsed.conditions.length === 0) throw new Error("sheet-data.json has no conditions");
for (const c of parsed.conditions) {
  if (typeof c.id !== "string" || !/^[a-z0-9-]+$/.test(c.id)) throw new Error(`bad condition id: ${JSON.stringify(c.id)}`);
}

// The links file: ids, names and FAA URLs only. Sources in first-seen order, the letter's first. Deterministic (same
// data, same bytes), and refused if it could carry anything else.
const FAA = /^https:\/\/(www\.faa\.gov|www\.ecfr\.gov)\/[^\s"<>]*$/;
const LINKS_NOTE = "Made by SecureLink/server/tools/build-sheet.mjs from sheet-data.json. Condition ids, names and the FAA's " +
  "own URLs only, no FAA words. The page shows these links while the quotes are being re-checked.";
const links = { note: LINKS_NOTE, conditions: parsed.conditions.map((c) => {
  const sources = [];
  for (const u of [...(c.letter ? [c.letter.sourceURL] : []), ...c.blocks.map((b) => b.sourceURL)]) if (!sources.includes(u)) sources.push(u);
  return { id: c.id, name: c.name, page: c.page, sources };
}) };
const faaWords = new Set();
for (const c of parsed.conditions) {
  if (c.letter) faaWords.add(c.letter.quote);
  for (const b of c.blocks) {
    faaWords.add(b.title);
    for (const q of b.quotes) {
      if (typeof q === "string") { faaWords.add(q); continue; }
      faaWords.add(q.quote);
      for (const x of Array.isArray(q.sub) ? q.sub : []) faaWords.add(x);
    }
  }
}
for (const c of links.conditions) {
  if (JSON.stringify(Object.keys(c)) !== '["id","name","page","sources"]') throw new Error("links: unexpected field");
  if (typeof c.name !== "string" || !c.name.trim() || c.name.length > 80 || /[\u2013\u2014<>]/.test(c.name)) throw new Error(`links: bad name for ${c.id}`);
  for (const u of [c.page, ...c.sources]) if (typeof u !== "string" || !FAA.test(u)) throw new Error(`links: not an FAA URL for ${c.id}: ${u}`);
  if (c.sources.length === 0) throw new Error(`links: no sources for ${c.id}`);
}
const linksText = JSON.stringify(links, null, 1) + "\n";
for (const w of faaWords) if (typeof w === "string" && w.trim() && linksText.includes(JSON.stringify(w).slice(1, -1))) {
  throw new Error(`links: would carry FAA words: ${JSON.stringify(w).slice(0, 80)}`);
}
writeFileSync(join(root, "viewer", "sheet", "sheet-links.json"), linksText);

mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
writeFileSync(join(here, "..", "src", "generated", "sheet.mjs"),
  `// GENERATED by tools/build-sheet.mjs. Do not edit.\n` +
  `export const SHEET_SCRIPT_HASH = ${JSON.stringify(hash(script))};\n` +
  `export const SHEET_STYLE_HASH = ${JSON.stringify(hash(style))};\n` +
  `export const SHEET_HTML = ${JSON.stringify(html)};\n` +
  `export const SHEET_DATA = ${JSON.stringify(data)};\n` +
  `export const SHEET_LINKS = ${JSON.stringify(linksText)};\n`);
console.log("sheet built:", html.length, "bytes page,", data.length, "chars data,", parsed.conditions.length, "conditions,", linksText.length, "chars links");
