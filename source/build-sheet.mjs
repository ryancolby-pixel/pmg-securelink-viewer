// Builds the AME request sheet the server serves at GET /sheet: viewer/sheet/index.html (one inline style, one inline
// script) and viewer/sheet/sheet-data.json (made by tools/build-sheet-data.py, FAA words only), and pins the style and
// script SHA-256 hashes for the Content-Security-Policy. Output: src/generated/sheet.mjs (committed), so the Lambda
// and the local server serve the same bytes. The page holds no pilot data; it can fetch only its own data file.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const hash = (s) => `sha256-${createHash("sha256").update(s, "utf8").digest("base64")}`;

const html = read("viewer/sheet/index.html");
const data = read("viewer/sheet/sheet-data.json");

// Our page. The data file is the FAA's words, verbatim, so its dashes stay.
if (/\u2014|\u2013/.test(html)) throw new Error("no em or en dashes in the sheet page");
if (/<script[^>]+src=|<link[^>]+href=/i.test(html)) throw new Error("the sheet must load nothing from elsewhere");

// Exactly one bare <style> and one bare <script>, so the two hashes cover everything the page runs.
const inner = (tag) => {
  const opens = html.match(new RegExp(`<${tag}\\b[^>]*>`, "gi")) || [];
  if (opens.length !== 1 || opens[0] !== `<${tag}>`) throw new Error(`the sheet needs exactly one <${tag}> with no attributes`);
  return html.split(`<${tag}>`)[1].split(`</${tag}>`)[0];
};
const script = inner("script"), style = inner("style");
// The CSP blocks inline handlers and style attributes; refuse them here rather than ship a page that silently breaks.
const markup = html.replace(script, "").replace(style, "");
if (/\son[a-z]+\s*=|\sstyle\s*=/i.test(markup)) throw new Error("no inline event handlers or style attributes in the sheet");

const parsed = JSON.parse(data);
if (!Array.isArray(parsed.conditions) || parsed.conditions.length === 0) throw new Error("sheet-data.json has no conditions");
for (const c of parsed.conditions) {
  if (typeof c.id !== "string" || !/^[a-z0-9-]+$/.test(c.id)) throw new Error(`bad condition id: ${JSON.stringify(c.id)}`);
}

mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
writeFileSync(join(here, "..", "src", "generated", "sheet.mjs"),
  `// GENERATED by tools/build-sheet.mjs. Do not edit.\n` +
  `export const SHEET_SCRIPT_HASH = ${JSON.stringify(hash(script))};\n` +
  `export const SHEET_STYLE_HASH = ${JSON.stringify(hash(style))};\n` +
  `export const SHEET_HTML = ${JSON.stringify(html)};\n` +
  `export const SHEET_DATA = ${JSON.stringify(data)};\n`);
console.log("sheet built:", html.length, "bytes page,", data.length, "chars data,", parsed.conditions.length, "conditions");
