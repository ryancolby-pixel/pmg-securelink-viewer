// Builds the standalone viewer: inlines shared/pmgl.mjs (exports stripped) + viewer.js + viewer.css into viewer.html,
// and pins their SHA-256 hashes for the Content-Security-Policy. Output: src/generated/viewer.mjs (committed).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const pmgl = read("shared/pmgl.mjs")
  .split("\n")
  .filter((l) => !l.startsWith("export {"))
  .map((l) => l.replace(/^export (async function|function|class|const)/, "$1"))
  .join("\n");
const script = `\n${pmgl}\n${read("viewer/viewer.js")}\n`;
const style = `\n${read("viewer/viewer.css")}\n`;
const hash = (s) => `sha256-${createHash("sha256").update(s, "utf8").digest("base64")}`;

const html = read("viewer/viewer.html").replace("/*__STYLE__*/", () => style).replace("/*__SCRIPT__*/", () => script);
if (/—|–/.test(html)) throw new Error("no em or en dashes in the viewer");
if (/<script[^>]+src=|<link[^>]+href=/i.test(html)) throw new Error("the viewer must load nothing from elsewhere");

mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
writeFileSync(join(here, "..", "src", "generated", "viewer.mjs"),
  `// GENERATED by tools/build-viewer.mjs. Do not edit.\n` +
  `export const SCRIPT_HASH = ${JSON.stringify(hash(script))};\n` +
  `export const STYLE_HASH = ${JSON.stringify(hash(style))};\n` +
  `export const VIEWER_HTML = ${JSON.stringify(html)};\n`);
console.log("viewer built:", html.length, "bytes");
